import joplin from 'api';
import { FileSystemItem, ImportContext, SettingItemType } from 'api/types';
import { importChatGptArchive } from './chatgpt-import';
import { importClaudeExport } from './claude-import';

joplin.plugins.register({
	onStart: async function() {
		// Register settings section. The id predates Claude support and is
		// kept so that existing settings are preserved.
		await joplin.settings.registerSection('chatgptImport', {
			label: 'AI Chat Import',
			iconName: 'fas fa-comments',
		});

		// Register settings
		await joplin.settings.registerSettings({
			'userName': {
				value: 'User',
				type: SettingItemType.String,
				section: 'chatgptImport',
				public: true,
				label: 'User name',
				description: 'Display name for user messages in imported conversations',
			},
			'assistantName': {
				value: 'ChatGPT',
				type: SettingItemType.String,
				section: 'chatgptImport',
				public: true,
				label: 'ChatGPT assistant name',
				description: 'Display name for assistant messages in imported ChatGPT conversations',
			},
			'claudeAssistantName': {
				value: 'Claude',
				type: SettingItemType.String,
				section: 'chatgptImport',
				public: true,
				label: 'Claude assistant name',
				description: 'Display name for assistant messages in imported Claude conversations',
			},
			'titleFormat': {
				value: '{date} {title}',
				type: SettingItemType.String,
				section: 'chatgptImport',
				public: true,
				label: 'Note title format',
				description: 'Format for note titles. Placeholders: {title}, {date}, {date:FORMAT}, {time}. FORMAT can use YYYY, YY, MM, M, DD, D.',
			},
			'includeDate': {
				value: false,
				type: SettingItemType.Bool,
				section: 'chatgptImport',
				public: true,
				label: 'Show date in note body',
				description: 'Display the conversation date at the top of the note body',
			},
			'useCollapsibleThinking': {
				value: true,
				type: SettingItemType.Bool,
				section: 'chatgptImport',
				public: true,
				label: 'Use collapsible sections',
				description: 'Wrap tool outputs and context in collapsible <details> sections',
			},
			'toolCalls': {
				value: 'hide',
				type: SettingItemType.String,
				isEnum: true,
				options: {
					full: 'Full',
					callOnly: 'Call only',
					hide: 'Hide',
				},
				section: 'chatgptImport',
				public: true,
				label: 'Tool calls',
				description: 'How tool calls (web searches, file reads, connectors...) are shown. "Call only" shows the tool and its input without the output. Images generated by a tool are always kept.',
			},
			'includeThinking': {
				value: false,
				type: SettingItemType.Bool,
				section: 'chatgptImport',
				public: true,
				label: 'Include thinking/reasoning',
				description: 'Include internal thinking and reasoning messages from the assistant',
			},
			'quoteUserMessages': {
				value: true,
				type: SettingItemType.Bool,
				section: 'chatgptImport',
				public: true,
				label: 'Quote user messages',
				description: 'Display user messages in blockquotes to distinguish them from assistant messages',
			},
		});

		await joplin.interop.registerImportModule({
			format: 'chatgpt',
			description: 'ChatGPT Export (ZIP)',
			isNoteArchive: true,
			sources: [FileSystemItem.File],
			fileExtensions: ['zip'],
			onExec: async (context: ImportContext) => importChatGptArchive(context),
		});

		// Claude exports come as several zips, which the user downloads into
		// one folder.
		await joplin.interop.registerImportModule({
			format: 'claude',
			description: 'Claude Export (folder)',
			isNoteArchive: true,
			sources: [FileSystemItem.Directory],
			onExec: async (context: ImportContext) => importClaudeExport(context),
		});

		console.info('AI Chat Import plugin started');
	},
});
